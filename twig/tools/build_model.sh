#!/usr/bin/env bash
# Selective firmware build: turn a transpiled `.model` into a twig-oop image containing
# exactly the drivers that model references, plus the fixed core.
#
# Pipeline (Phase 11): compatibility-check -> emit driver selection -> embed the model ->
# idf.py build (optionally boot under QEMU).
#
# Usage: ./build_model.sh <model-file.model> [--qemu] [--seconds N] [--skip-check]
#   --qemu         also boot the built image under QEMU (via run_qemu.sh).
#   --seconds N    QEMU capture window in seconds (default 40).
#   --skip-check   skip the compatibility gate and driver selection (embed + build only).
#
# Exit status: 0 on success; 1 if the model is incompatible (report printed); 2 on usage/
# IO error.
#
# Deploy (deliberately scoped down): with a single real board target there is no
# multi-target/fleet flashing here. Flash the resulting image per device with:
#   idf.py -p <PORT> flash monitor
# (QEMU-only validation for now: ./run_model.sh <model>).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"

MODEL="${1:?Usage: $0 <model-file.model> [--qemu] [--seconds N] [--skip-check]}"
shift

RUN_QEMU=0
SECONDS_TO_CAPTURE=40
SKIP_CHECK=0

while [ $# -gt 0 ]; do
    case "$1" in
        --qemu) RUN_QEMU=1 ;;
        --seconds) SECONDS_TO_CAPTURE="${2:?--seconds requires a value}"; shift ;;
        --skip-check) SKIP_CHECK=1 ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
    shift
done

if [ ! -f "$MODEL" ]; then
    echo "error: model file not found: $MODEL" >&2
    exit 2
fi

# The generated per-model driver selection fragment (see components/drivers/Kconfig).
SELECTION="$ROOT_DIR/main/driver_selection.defaults"

if [ "$SKIP_CHECK" = "0" ]; then
    CHECKER="$SCRIPT_DIR/compat_checker/build/checker"
    "$SCRIPT_DIR/compat_checker/ensure_built.sh"

    # Emit the selection matrix (also performs the full check: on any finding, the
    # checker exits non-zero and prints the report, and we stop without building).
    if ! "$CHECKER" --emit-selection "$MODEL" > "$SELECTION"; then
        echo "error: model is incompatible with twig-oop (see report above); not building" >&2
        exit 1
    fi

    # This is a real deployment image for ONE specific model, not a bring-up/dev build --
    # drop the on-device self-test suite (naxe/cil/stick) to reclaim the ~115 KB of BSS
    # its own static buffers would otherwise cost on top of this model's own runtime
    # buffers (see main/Kconfig.projbuild). --skip-check builds (quick raw-build
    # iteration) keep the default y, i.e. still self-test.
    echo "CONFIG_TWIG_ONDEVICE_SELFTEST=n" >> "$SELECTION"

    echo "=== driver selection ==="
    cat "$SELECTION"
else
    rm -f "$SELECTION"
fi

if [ "$SKIP_CHECK" = "0" ]; then
    # Force a kconfig regeneration when the driver set changes. ESP-IDF only merges the
    # sdkconfig.defaults on a FRESH config, and the -DSDKCONFIG_DEFAULTS argument string is
    # identical across runs (same file path), so a content-only change would otherwise be
    # ignored. Deleting sdkconfig (regenerated from defaults on the next build) makes the
    # new driver selection take effect; an unchanged selection skips this, keeping
    # repeated builds of one model fast.
    APPLIED="$ROOT_DIR/build/.driver_selection.applied"
    if [ ! -f "$APPLIED" ] || ! cmp -s "$SELECTION" "$APPLIED"; then
        mkdir -p "$ROOT_DIR/build"
        rm -f "$ROOT_DIR/sdkconfig"
        cp "$SELECTION" "$APPLIED"
    fi
fi

# Embed the model into firmware (the plan's "compile-time config": each image carries
# its model). Same generator as tools/run_model.sh.
DELIM="MINGLE_MODEL"
{
    echo "/*"
    echo " * Licensed under the Apache License, Version 2.0 (the \"License\");"
    echo " * you may not use this file except in compliance with the License."
    echo " * You may obtain a copy of the License at"
    echo " *"
    echo " *      http://www.apache.org/licenses/LICENSE-2.0"
    echo " *"
    echo " * Unless required by applicable law or agreed to in writing, software"
    echo " * distributed under the License is distributed on an \"AS IS\" BASIS,"
    echo " * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied."
    echo " * See the License for the specific language governing permissions and"
    echo " * limitations under the License."
    echo " */"
    echo "/** \file model_data.hpp"
    echo " *"
    echo " * GENERATED by tools/build_model.sh from: $MODEL"
    echo " * (do not edit by hand — the next run overwrites this file)."
    echo " */"
    echo "#pragma once"
    echo ""
    echo "namespace app"
    echo "{"
    echo "    /** The model JSON source, as a NUL-terminated string. */"
    echo "    inline const char * kModelJson ="
    printf '        R"%s(\n' "$DELIM"
    cat "$MODEL"
    printf ')%s";\n' "$DELIM"
    echo "} // namespace app"
} > "$ROOT_DIR/main/model_data.hpp"

echo "=== Executing model: $MODEL ==="

if [ "$RUN_QEMU" = "1" ]; then
    # run_qemu.sh is the single build entry point; it reads MINGLE_DRIVER_DEFAULTS and
    # applies the selection to its own idf.py build.
    MINGLE_DRIVER_DEFAULTS="$SELECTION" exec "$ROOT_DIR/run_qemu.sh" "$SECONDS_TO_CAPTURE"
fi

(
    cd "$ROOT_DIR"
    # shellcheck disable=SC1090
    source "$HOME/esp/esp-idf/export.sh" > /dev/null
    if [ -f "$SELECTION" ]; then
        idf.py -DSDKCONFIG_DEFAULTS="sdkconfig.defaults;$SELECTION" build
    else
        idf.py build
    fi
)
